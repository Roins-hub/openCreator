/** 把中转站返回的 message / message_key / message_params 换成中文;没有译文时原样返回 */
export function relayMessage(body: { message?: unknown; message_key?: unknown; message_params?: unknown } | null | undefined) {
  const key = typeof body?.message_key === "string" ? body.message_key : "";
  const message = typeof body?.message === "string" ? body.message : "";
  const template = ZH[key] ?? ZH[message];
  if (!template) return message;
  const params = body?.message_params && typeof body.message_params === "object" ? body.message_params as Record<string, unknown> : {};
  return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}
